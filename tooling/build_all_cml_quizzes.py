"""
Compiler for Classical Machine Learning Quizzes (Lectures 01 to 15).
Consolidates all CML quiz modules and compiles web/src/data/subjects/classical-machine-learning/quizzesData.ts.
"""

import json
from pathlib import Path
import sys

BASE_DIR = Path(__file__).parent.parent
CML_QUIZZES_DIR = BASE_DIR / "tooling" / "cml_quizzes"
OUTPUT_TS = BASE_DIR / "web" / "src" / "data" / "subjects" / "classical-machine-learning" / "quizzesData.ts"

sys.path.insert(0, str(CML_QUIZZES_DIR))

from lecture_01 import QUIZ_L01
from lecture_02 import QUIZ_L02
from lecture_03 import QUIZ_L03
from lecture_04 import QUIZ_L04
from lecture_05 import QUIZ_L05
from lecture_06 import QUIZ_L06
from lecture_07 import QUIZ_L07
from lecture_08 import QUIZ_L08
from lecture_09 import QUIZ_L09
from lecture_10 import QUIZ_L10
from lecture_11 import QUIZ_L11
from lecture_12 import QUIZ_L12
from lecture_13 import QUIZ_L13
from lecture_14 import QUIZ_L14
from lecture_15 import QUIZ_L15
from lecture_16 import QUIZ_L16

ALL_CML_QUIZZES = {
    "lecture-01": QUIZ_L01,
    "lecture-02": QUIZ_L02,
    "lecture-03": QUIZ_L03,
    "lecture-04": QUIZ_L04,
    "lecture-05": QUIZ_L05,
    "lecture-06": QUIZ_L06,
    "lecture-07": QUIZ_L07,
    "lecture-08": QUIZ_L08,
    "lecture-09": QUIZ_L09,
    "lecture-10": QUIZ_L10,
    "lecture-11": QUIZ_L11,
    "lecture-12": QUIZ_L12,
    "lecture-13": QUIZ_L13,
    "lecture-14": QUIZ_L14,
    "lecture-15": QUIZ_L15,
    "lecture-16": QUIZ_L16,
}

def main():
    print(f"Compiling {len(ALL_CML_QUIZZES)} Classical Machine Learning quiz modules...")
    
    total_q = 0
    for topic_id, quiz in ALL_CML_QUIZZES.items():
        q_count = len(quiz["questions"])
        total_q += q_count
        print(f"  - {topic_id} ({quiz['title']}): {q_count} questions")
        
        # Basic validation
        assert quiz["topicId"] == topic_id, f"topicId mismatch in {topic_id}"
        for q in quiz["questions"]:
            assert "id" in q, f"Missing id in {topic_id}"
            assert "question" in q, f"Missing question in {q['id']}"
            assert "options" in q, f"Missing options in {q['id']}"
            assert "correctOptionIds" in q and len(q["correctOptionIds"]) > 0, f"Missing correctOptionIds in {q['id']}"
            assert "explanation" in q, f"Missing explanation in {q['id']}"

    ts_code = "// Auto-generated by build_all_cml_quizzes.py - DO NOT EDIT DIRECTLY\n"
    ts_code += "import type { TopicQuiz } from '../../../types/quiz';\n\n"
    ts_code += f"export const quizzesRegistry: Record<string, TopicQuiz> = {json.dumps(ALL_CML_QUIZZES, indent=2, ensure_ascii=False)};\n"

    OUTPUT_TS.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_TS.write_text(ts_code, encoding="utf-8")
    print(f"\nSuccessfully compiled {total_q} questions across {len(ALL_CML_QUIZZES)} lectures into {OUTPUT_TS}")

if __name__ == "__main__":
    main()
